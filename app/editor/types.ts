import type { FinisherSource } from "./stravaStickers";

export type FormatId = "story" | "post" | "square";

export type Format = { id: FormatId; label: string; ratio: string; w: number; h: number };

export const FORMATS: Format[] = [
  { id: "story", label: "Story", ratio: "9:16", w: 1080, h: 1920 },
  { id: "post", label: "Post", ratio: "4:5", w: 1080, h: 1350 },
  { id: "square", label: "Square", ratio: "1:1", w: 1080, h: 1080 },
];

export type Rect = { x: number; y: number; w: number; h: number };

/** Background split: one photo, two side by side, or two stacked top & bottom. */
export type Split = "none" | "side" | "stacked";

/** Width of the white line between split photos, in design units. */
export const DIVIDER = 6;

/** The background panes (design units) for a split: [first] or [first, second]. */
export function panes(f: Format, split: Split): Rect[] {
  if (split === "side") return [{ x: 0, y: 0, w: f.w / 2, h: f.h }, { x: f.w / 2, y: 0, w: f.w / 2, h: f.h }];
  if (split === "stacked") return [{ x: 0, y: 0, w: f.w, h: f.h / 2 }, { x: 0, y: f.h / 2, w: f.w, h: f.h / 2 }];
  return [{ x: 0, y: 0, w: f.w, h: f.h }];
}

/** Shared transform for anything placed on the canvas. x/y are the center, in design units (output px at 1x). */
export type Transform = { x: number; y: number; scale: number; rotation: number };

export type ImageLayer = Transform & {
  id: string;
  src: string;
  img: HTMLImageElement;
  nw: number;
  nh: number;
};

export type Sticker = ImageLayer & {
  opacity: number;
  /** Generated by a layout (e.g. the timeline line); replaced whenever the layout is re-applied. */
  deco?: boolean;
  /** A value layouts can size by (e.g. run distance in meters). */
  weight?: number;
  /** How a generated sticker was made, so it can be edited and re-rendered in place. */
  edit?: FinisherSource;
};

export type Background = ImageLayer;

export async function loadImage(file: Blob): Promise<{ src: string; img: HTMLImageElement; nw: number; nh: number }> {
  const src = URL.createObjectURL(file);
  const img = new Image();
  img.src = src;
  await img.decode();
  return { src, img, nw: img.naturalWidth, nh: img.naturalHeight };
}

export const uid = () => Math.random().toString(36).slice(2, 10);
